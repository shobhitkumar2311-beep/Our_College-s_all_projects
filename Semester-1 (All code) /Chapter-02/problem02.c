/* What data type will 3.0/8 – 2 return? */
#include <stdio.h>
int main()
{
    float result = 3.0 / 8 - 2;
    // The Float data type will be returned integers ans the decimal value so in this case we use the float datatype in the code.
    printf("The result of 3.0/8 - 2 is: %f\n", result);
    // The result of 3.0/8 - 2 is: -1.625000
    return 0;
}
